import { WORKED_EXAMPLES } from '@/data/workedExamples';
import { formatDuration, formatWatts, formatWh } from '@/lib/formatting';

export function WorkedExamples() {
  return (
    <section className="mx-auto max-w-6xl px-4 py-12 sm:px-6">
      <h2 className="section-heading">Worked examples</h2>
      <p className="mt-2 text-navy-600">
        These figures are generated by the same calculation engine used by the calculator, so they stay consistent.
      </p>
      <div className="mt-6 grid gap-4 sm:grid-cols-2">
        {WORKED_EXAMPLES.map((example) => {
          const { result, input } = example;
          const enabledDevices = input.devices.filter((d) => d.enabled);
          return (
            <div key={example.id} className="card p-5">
              <h3 className="text-base font-semibold text-navy-900">{example.title}</h3>
              <p className="mt-1 text-sm text-navy-600">{example.description}</p>

              <dl className="mt-4 space-y-1.5 text-sm">
                <Row label="Battery" value={`${formatWh(input.nominalWh)} nominal, 80% usable, 10% reserve`} />
                <Row label="Devices" value={enabledDevices.map((d) => `${d.name} (${formatWatts(d.watts)})`).join(', ')} />
                <Row label="AC efficiency" value="85%" />
                <Row label="Battery-side draw" value={formatWatts(result.batteryDrawW)} />
                <Row label="Runtime" value={formatDuration(result.runtimeHours ?? 0)} />
              </dl>
            </div>
          );
        })}
      </div>
    </section>
  );
}

function Row({ label, value }: { label: string; value: string }) {
  return (
    <div className="flex flex-col gap-0.5">
      <dt className="text-xs font-medium uppercase tracking-wide text-navy-600/60">{label}</dt>
      <dd className="text-navy-900">{value}</dd>
    </div>
  );
}
